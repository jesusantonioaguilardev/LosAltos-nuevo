/* Cambio de idioma: guarda el texto original de cada nodo y lo sustituye por su traducción.
 * El idioma se elige con los botones .idioma [data-lang] y se recuerda en el navegador.
 * También se puede abrir directo en inglés con ?lang=en */
(function () {
  'use strict';
  var EN = window.LA_EN || {};
  var CLAVE = 'la-idioma';
  var textos = [], atributos = [];
  var meta = document.querySelector('meta[name="description"]');
  var original = { titulo: document.title, meta: meta ? meta.content : '' };

  function norm(s) { return s.replace(/\s+/g, ' ').trim(); }

  function recolectar() {
    var paseo = document.createTreeWalker(document.body, NodeFilter.SHOW_TEXT, {
      acceptNode: function (n) {
        if (!norm(n.nodeValue)) return NodeFilter.FILTER_REJECT;
        if (n.parentElement.closest('script,style,svg,noscript,.idioma')) return NodeFilter.FILTER_REJECT;
        return NodeFilter.FILTER_ACCEPT;
      }
    });
    while (paseo.nextNode()) textos.push({ nodo: paseo.currentNode, original: paseo.currentNode.nodeValue });
    document.querySelectorAll('[alt],[aria-label],[title],[placeholder]').forEach(function (el) {
      if (el.closest('.idioma')) return;
      ['alt', 'aria-label', 'title', 'placeholder'].forEach(function (a) {
        var v = el.getAttribute(a);
        if (v) atributos.push({ el: el, attr: a, original: v });
      });
    });
  }

  function aplicar(lang) {
    var en = lang === 'en';
    textos.forEach(function (t) {
      var k = norm(t.original);
      if (en && EN[k]) {
        t.nodo.nodeValue = t.original.match(/^\s*/)[0] + EN[k] + t.original.match(/\s*$/)[0];
      } else {
        t.nodo.nodeValue = t.original;
      }
    });
    atributos.forEach(function (a) {
      var k = norm(a.original);
      a.el.setAttribute(a.attr, en && EN[k] ? EN[k] : a.original);
    });
    document.title = en && EN[original.titulo] ? EN[original.titulo] : original.titulo;
    if (meta) meta.content = en && EN[original.meta] ? EN[original.meta] : original.meta;
    document.documentElement.lang = en ? 'en' : 'es-MX';
    document.querySelectorAll('.idioma [data-lang]').forEach(function (b) {
      b.setAttribute('aria-pressed', b.getAttribute('data-lang') === lang ? 'true' : 'false');
    });
    try { localStorage.setItem(CLAVE, lang); } catch (e) { /* sin almacenamiento */ }
    // Avisa a otros scripts (por ejemplo, el botón del menú) que cambió el idioma
    document.dispatchEvent(new CustomEvent('la:idioma', { detail: lang }));
  }

  function iniciar() {
    recolectar();
    document.querySelectorAll('.idioma [data-lang]').forEach(function (b) {
      b.addEventListener('click', function () { aplicar(b.getAttribute('data-lang')); });
    });
    var pedido = new URLSearchParams(location.search).get('lang');
    var guardado = null;
    try { guardado = localStorage.getItem(CLAVE); } catch (e) { /* sin almacenamiento */ }
    var lang = pedido || guardado || 'es';
    aplicar(lang === 'en' ? 'en' : 'es');
  }
  window.LA_idioma = function () { return document.documentElement.lang === 'en' ? 'en' : 'es'; };
  if (document.readyState === 'loading') document.addEventListener('DOMContentLoaded', iniciar);
  else iniciar();
})();
